@pytest.mark.skipif(importlib.util.find_spec("pinocchio") is None, reason="pinocchio not installed")
def test_extended_reset_pose_puts_the_palm_down_in_front_of_the_right_shoulder(build_script):
    import pinocchio as pin

    model = pin.buildModelFromUrdf(str(URDF))
    data = model.createData()
    q = pin.neutral(model)
    for name, value in zip(build_script.RIGHT_ARM_JOINTS, build_script.DEFAULT_RIGHT_ARM_POSE, strict=True):
        q[model.joints[model.getJointId(name)].idx_q] = value
    pin.forwardKinematics(model, data, q)
    pin.updateFramePlacements(model, data)
    palm = data.oMf[model.getFrameId("right_hand_C_MC")]
    assert palm.translation == pytest.approx(build_script.RESET_POSE_TARGET_POSITION, abs=1e-4)
    expected = np.array(build_script.RESET_POSE_TARGET_ROTATION, dtype=np.float64)
    assert np.allclose(palm.rotation, expected, atol=1e-4)
    assert palm.rotation[:, 0] == pytest.approx([0.0, 0.0, -1.0], abs=1e-4)  # palm normal straight down
    elbow = data.oMf[model.getFrameId("Arm_R4_Link")].translation
    shoulder = data.oMf[model.getFrameId("Arm_R1_Link")].translation
    assert shoulder == pytest.approx([0.0, -0.2005, 1.203], abs=1e-3)
    assert elbow[2] < shoulder[2] - 0.2 and elbow[1] < shoulder[1]  # elbow below and outside the shoulder
    # With the bench placement the palm hovers 0.35 m above the 0.75 m tabletop, over the table.
    arm = load_wrist_bench_arms().arm("tianji")
    world = palm.translation + np.array(arm.robot.position)
    assert world[2] - 0.75 == pytest.approx(0.35, abs=1e-3) and -0.245 < world[0] < 0.245
