"""Static checks of the Tianji Marvin M6 CCS + right Sharpa asset against Tianji's official flange data.

The asset is generated by ``dex_teleop/scripts/build_tianji_sharpa_right.py`` into the (git-ignored)
robot dataset; these tests read that output, the upstream dual-arm model it derives from, and the
build script's constants, and skip when the dataset is not present.
"""

from __future__ import annotations

import importlib.util
import math
from pathlib import Path
import struct
import xml.etree.ElementTree as ET

import numpy as np
import pytest
from scipy.spatial.transform import Rotation
import yaml

from dex_teleop.hand_bench import load_wrist_bench_arms
from dex_teleop.hands import SHARPA_ACTION_JOINTS


REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
ROBOT_ASSETS = REPOSITORY_ROOT / "datasets" / "omnigibson-robot-assets"
MODEL_ROOT = ROBOT_ASSETS / "models" / "tianji_m6_ccs_sharpa_right"
URDF = MODEL_ROOT / "urdf" / "tianji_m6_ccs_sharpa_right.urdf"
DEFINITION = MODEL_ROOT / "tianji_m6_ccs_sharpa_right.yaml"
UPSTREAM_URDF = ROBOT_ASSETS / "source" / "tianji_m6_ccs" / "tianji_m6_ccs_source.urdf"
BUILD_SCRIPT = REPOSITORY_ROOT / "dex_teleop" / "scripts" / "build_tianji_sharpa_right.py"

# Tianji's published M6 CCS geometry: J2 axis to end flange (data sheet), and the link offsets
# of the official URDF / ccs_m6_40.MvKDCfg that add up to it.
OFFICIAL_REACH_M = 0.696
OFFICIAL_UPPER_ARM_M = 0.287
OFFICIAL_FOREARM_M = 0.314
OFFICIAL_FLANGE_M = 0.095
ISO_9409_1_50_PCD_RADIUS_M = 0.025

pytestmark = pytest.mark.skipif(not URDF.is_file(), reason="tianji_m6_ccs_sharpa_right asset not built")


@pytest.fixture(scope="module")
def build_script():
    spec = importlib.util.spec_from_file_location("build_tianji_sharpa_right", BUILD_SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def root():
    return ET.parse(URDF).getroot()


def _joint(root: ET.Element, name: str) -> ET.Element:
    matches = [joint for joint in root.findall("joint") if joint.get("name") == name]
    assert len(matches) == 1, name
    return matches[0]


def _link(root: ET.Element, name: str) -> ET.Element:
    matches = [link for link in root.findall("link") if link.get("name") == name]
    assert len(matches) == 1, name
    return matches[0]


def _origin(element: ET.Element) -> tuple[np.ndarray, np.ndarray]:
    origin = element.find("origin")
    xyz = np.array([float(v) for v in origin.get("xyz", "0 0 0").split()])
    rpy = np.array([float(v) for v in origin.get("rpy", "0 0 0").split()])
    return xyz, rpy


def _stl_vertices(path: Path) -> np.ndarray:
    data = path.read_bytes()
    (count,) = struct.unpack_from("<I", data, 80)
    assert 84 + 50 * count == len(data), "binary STL expected"
    triangles = np.frombuffer(data, dtype=np.uint8, count=50 * count, offset=84).reshape(count, 50)
    return triangles[:, 12:48].copy().view("<f4").reshape(-1, 3).astype(np.float64)


def test_sharpa_hand_sits_on_the_official_95_mm_flange_pin_aligned(root, build_script):
    attachment = _joint(root, build_script.ATTACHMENT_JOINT)
    assert attachment.get("type") == "fixed"
    assert attachment.find("parent").get("link") == "Arm_R7_Link"
    assert attachment.find("child").get("link") == "right_hand_flange"
    xyz, rpy = _origin(attachment)
    # 95 mm from the J7 axis along Link7 -Y: Tianji's tool frame (ccs_m6_40.MvKDCfg d = 95) and the
    # Link7_R.STL flange face; with the 287 + 314 mm links it closes the published 696 mm reach.
    assert xyz == pytest.approx([0.0, -OFFICIAL_FLANGE_M, 0.0])
    assert OFFICIAL_UPPER_ARM_M + OFFICIAL_FOREARM_M + OFFICIAL_FLANGE_M == pytest.approx(OFFICIAL_REACH_M)
    rotation = Rotation.from_euler("xyz", rpy)
    # Hand axis (Sharpa +Z) along the outward flange normal, palm normal / pin (Sharpa +X) on Link7 +X,
    # pinky-to-thumb axis (Sharpa +Y) on the J7 axis (Link7 +Z).
    assert rotation.apply([0.0, 0.0, 1.0]) == pytest.approx([0.0, -1.0, 0.0], abs=1e-6)
    assert rotation.apply([1.0, 0.0, 0.0]) == pytest.approx([1.0, 0.0, 0.0], abs=1e-6)
    assert rotation.apply([0.0, 1.0, 0.0]) == pytest.approx([0.0, 0.0, 1.0], abs=1e-6)
    # Equal to Tianji's own tool-frame orientation (modified DH alpha=90, theta=90) followed by the
    # -90 degree pin alignment, i.e. the Gento flange_R orientation times Rz(-90).
    upstream = ET.parse(UPSTREAM_URDF).getroot()
    _, flange_rpy = _origin(_joint(upstream, "Arm_R7_Link_to_flange_R"))
    composed = Rotation.from_euler("xyz", flange_rpy) * Rotation.from_euler("z", -math.pi / 2)
    assert (composed.inv() * rotation).magnitude() < 1e-4  # the Gento rpy are rounded to 1e-7
    # The Gento frame sits 7 mm inside the physical face; it is not used.
    flange_xyz, _ = _origin(_joint(upstream, "Arm_R7_Link_to_flange_R"))
    assert flange_xyz == pytest.approx([0.0, -0.088, 0.0])
    assert not any(joint.find("child").get("link") == "flange_R" for joint in root.findall("joint"))


def test_official_link7_mesh_carries_an_iso_9409_1_50_4_m6_flange_at_95_mm():
    vertices = _stl_vertices(MODEL_ROOT / "urdf" / "meshes" / "marvin_pro" / "meshes" / "m6" / "Arm_R7_Link.STL")
    # The flange face is the mesh's -Y extreme, exactly at the official tool offset.
    assert vertices[:, 1].min() == pytest.approx(-OFFICIAL_FLANGE_M, abs=1e-4)
    face_plane = vertices[vertices[:, 1] < vertices[:, 1].min() + 2e-4]
    plane_radius = np.hypot(face_plane[:, 0], face_plane[:, 2])
    assert plane_radius.max() == pytest.approx(0.031, abs=0.001)  # 62 mm face
    assert plane_radius.min() == pytest.approx(0.0162, abs=0.001)  # 31.5 mm centring recess
    # The bolt and pin bores run 13 mm into the link; take the vertices within 6 mm of the face.
    face = vertices[vertices[:, 1] < vertices[:, 1].min() + 0.006]
    radius = np.hypot(face[:, 0], face[:, 2])
    ring = face[(radius > 0.0215) & (radius < 0.0285)]
    angles = np.degrees(np.arctan2(ring[:, 2], ring[:, 0]))
    holes = []
    for centre in (-135.0, -45.0, 0.0, 45.0, 135.0):
        selected = ring[np.abs((angles - centre + 180.0) % 360.0 - 180.0) < 12.0]
        assert len(selected) > 20, centre
        cx, cz = selected[:, 0].mean(), selected[:, 2].mean()
        holes.append((np.hypot(cx, cz), np.degrees(np.arctan2(cz, cx))))
    for pcd_radius, angle in holes:
        assert pcd_radius == pytest.approx(ISO_9409_1_50_PCD_RADIUS_M, abs=0.0005)
    assert [round(angle) for _, angle in holes] == [-135, -45, 0, 45, 135]
    # No hole at +-90: four bolts at 45 degrees plus the pin at 0 (Link7 +X), not a six-hole pattern.
    assert not np.any(np.abs(np.abs(angles) - 90.0) < 12.0)


def test_sharpa_flange_adapter_matches_the_tianji_pattern_and_pin_direction():
    vertices = _stl_vertices(MODEL_ROOT / "urdf" / "meshes" / "sharpa" / "flange_B.STL")
    radius = np.hypot(vertices[:, 0], vertices[:, 1])
    assert radius.max() == pytest.approx(0.0315, abs=0.001)  # 63 mm rim, ISO 9409-1-A50
    # Robot-side pilot boss (z < 0): 31.5 mm centring diameter.
    boss = vertices[vertices[:, 2] < -0.0005]
    assert np.hypot(boss[:, 0], boss[:, 1]).max() == pytest.approx(0.01575, abs=0.0006)
    # Through holes on the 50 mm pitch circle at +-45/+-135 degrees, and the pin at 0 degrees (+X).
    mid = vertices[(vertices[:, 2] > 0.0005) & (vertices[:, 2] < 0.0075)]
    angles = np.degrees(np.arctan2(mid[:, 1], mid[:, 0]))
    ring = np.hypot(mid[:, 0], mid[:, 1])
    for centre in (-135.0, -45.0, 45.0, 135.0):
        selected = mid[(np.abs((angles - centre + 180.0) % 360.0 - 180.0) < 10.0) & (ring > 0.0205) & (ring < 0.0295)]
        assert len(selected) > 10, centre
        assert np.hypot(selected[:, 0].mean(), selected[:, 1].mean()) == pytest.approx(ISO_9409_1_50_PCD_RADIUS_M, abs=0.0015)
    pin = mid[(np.abs(angles) < 12.0) & (ring > 0.018) & (ring < 0.030)]
    assert len(pin) > 10 and pin[:, 1].mean() == pytest.approx(0.0, abs=0.002)


def test_merged_model_is_one_right_arm_plus_the_sharpa_hand(root):
    movable = [joint for joint in root.findall("joint") if joint.get("type") != "fixed"]
    names = [joint.get("name") for joint in movable]
    assert names[:7] == [f"Arm_R{i}_Joint" for i in range(1, 8)]
    assert set(names[7:]) == set(SHARPA_ACTION_JOINTS) and len(names) == 7 + len(SHARPA_ACTION_JOINTS)
    # The left arm and its gripper are welded at the upstream home pose; their links stay.
    for name in ("Arm_L1_Joint", "Arm_L7_Joint", "left_gripper_left_finger_joint"):
        joint = _joint(root, name)
        assert joint.get("type") == "fixed" and joint.find("axis") is None and joint.find("limit") is None
    left_home = yaml.safe_load((ROBOT_ASSETS / "models" / "tianji_m6_ccs" / "tianji_m6_ccs.yaml").read_text())
    _, l1_rpy = _origin(_joint(root, "Arm_L1_Joint"))
    assert Rotation.from_euler("xyz", l1_rpy).magnitude() == pytest.approx(abs(left_home["default_joint_pos"][0]), abs=1e-6)
    links = {link.get("name") for link in root.findall("link")}
    assert {"Arm_L7_Link", "left_gripper_base", "flange_L"} <= links
    assert not ({"flange_R", "right_gripper_base", "right_tool"} & links)
    children = {joint.find("child").get("link") for joint in root.findall("joint")}
    assert links - children == {"base_link"}  # one tree, rooted at the torso
    # Every link has positive mass (upstream frame links get the Sharpa fingertip placeholder).
    for link in root.findall("link"):
        assert float(link.find("inertial/mass").get("value")) > 0.0, link.get("name")


def test_torso_is_origined_at_the_floor_with_box_colliders(root):
    base = _link(root, "base_link")
    vertices = _stl_vertices(MODEL_ROOT / "urdf" / "meshes" / "marvin_pro" / "meshes" / "base" / "ZJ_Robot_link.STL")
    visual_xyz, _ = _origin(base.find("visual"))
    assert visual_xyz[2] == pytest.approx(-vertices[:, 2].min(), abs=1e-6)  # the plate's underside at z = 0
    boxes = base.findall("collision")
    assert len(boxes) == 4
    lowest = min(_origin(box)[0][2] - float(box.find("geometry/mesh").get("scale").split()[2]) / 2.0 for box in boxes)
    highest = max(_origin(box)[0][2] + float(box.find("geometry/mesh").get("scale").split()[2]) / 2.0 for box in boxes)
    assert lowest == pytest.approx(0.0, abs=1e-6)
    assert highest == pytest.approx(vertices[:, 2].max() + visual_xyz[2], abs=0.005)
    # The shoulders stay where the torso mesh puts them: 1.203 m above the floor.
    shoulder_xyz, _ = _origin(_joint(root, "base_link_to_Base_R"))
    assert shoulder_xyz == pytest.approx([0.0, -0.026, 1.203], abs=1e-6)


def test_robot_definition_matches_the_urdf_the_bench_and_the_sharpa_contract(root, build_script):
    definition = yaml.safe_load(DEFINITION.read_text(encoding="utf-8"))
    manipulation = definition["manipulation"]
    assert definition["raw_controller_order"] == ["arm_right", "gripper_right"]
    assert manipulation["n_arms"] == 1 and manipulation["arm_names"] == ["right"]
    assert manipulation["eef_link_names"]["right"] == "right_hand_C_MC"
    assert tuple(manipulation["finger_joint_names"]["right"]) == SHARPA_ACTION_JOINTS
    joint_names = {joint.get("name") for joint in root.findall("joint")}
    link_names = {link.get("name") for link in root.findall("link")}
    assert set(manipulation["arm_joint_names"]["right"]) <= joint_names
    assert set(manipulation["arm_link_names"]["right"]) <= link_names
    assert set(manipulation["finger_link_names"]["right"]) <= link_names
    assert definition["usd_path"] == "models/tianji_m6_ccs_sharpa_right/usd/tianji_m6_ccs_sharpa_right.usda"
    assert len(definition["default_joint_pos"]) == 7 + len(SHARPA_ACTION_JOINTS)
    # The definition's default arm pose is the bench's "extended" pose, and the build script's.
    arm = load_wrist_bench_arms().arm("tianji")
    assert definition["default_joint_pos"][:7] == pytest.approx(arm.reset_poses["extended"], abs=1e-6)
    assert list(build_script.DEFAULT_RIGHT_ARM_POSE) == pytest.approx(arm.reset_poses["extended"], abs=1e-6)
    assert arm.robot.model == definition["usd_path"].split("/")[1]
    lower = [float(_joint(root, name).find("limit").get("lower")) for name in manipulation["arm_joint_names"]["right"]]
    upper = [float(_joint(root, name).find("limit").get("upper")) for name in manipulation["arm_joint_names"]["right"]]
    for pose in arm.reset_poses.values():
        assert all(lo < q < hi for q, lo, hi in zip(pose, lower, upper, strict=True))


